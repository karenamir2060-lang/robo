// ======================================================
// OUTPUT — فرمت خروجی (JSON) و چک‌لیست قبل از جواب
// کلیدهای JSON با نسخه‌های قبلی یکیه؛ roboBrain.normalize بدون تغییر کار می‌کنه.
// وقتی مالک توی پیوی نیست، توضیحِ relay کوتاه می‌شه (همیشه null).
// وقتی ویس فعال نیست، voice همیشه false.
// ======================================================

function schema(f) {

    const relay = f.owner
        ? `{"chat_id":"شناسه‌ی گروه از <groups>","text":"پیامی که توی گروه می‌گی","reply_to":شماره‌ی یکی از پیام‌های <group_digest> یا null,"voice":true یا false} یا null`
        : "null";

    return `{"action":"ignore | react | reply","reaction":"یکی از ایموجی‌های مجاز یا null","reply_to":شماره‌ی پیام یا null,"text":"متن پیام تو","media":{"kind":"sticker | gif","mood":"یکی از حالت‌ها"} یا null,"voice":true یا false,"relay":${relay},"why":"دلیل خیلی کوتاه، حداکثر ۶ کلمه"}`;

}

function fields(f) {

    const lines = [
        "- ignore: چیزی نفرست؛ text خالی.",
        "- react: فقط ریکشن؛ text خالی.",
        "- reply: متن بفرست؛ می‌تونی همزمان reaction هم بذاری."
    ];

    if (f.media) {
        lines.push("- media: فقط با action=reply کار می‌کنه؛ نمی‌خوای؟ null. فقط استیکر یا گیف می‌فرستی؟ text خالی بذار.");
    }
    else {
        lines.push("- media: همیشه null.");
    }

    if (f.voice) {
        lines.push("- voice: فقط با action=reply و فقط وقتی <situation> اجازه‌ی ویس داده یا طرف (یا مالک) ویس خواسته. true یعنی text به‌صورت ویس فرستاده بشه. وقتی relay داری، ویس بودنِ پیامِ گروه رو relay.voice تعیین می‌کنه، نه این فیلد. ننوشتی یعنی false.");
    }
    else {
        lines.push("- voice: false.");
    }

    if (f.owner) {
        lines.push("- relay: فقط وقتی مالک توی پیوی ازت خواسته توی یه گروه چیزی بگی؛ chat_id باید دقیقاً یکی از شناسه‌های <groups> باشه. با action=reply بیا و توی text به مالک بگو چی شد. reply_to توی relay اختیاریه (ریپلای روی یکی از پیام‌های <group_digest>)؛ وگرنه null. relay.voice فقط وقتی true که مالک خواسته خودت توی گروه ویس بدی.");
    }
    else {
        lines.push("- relay: همیشه null.");
    }

    lines.push("- text فقط خودِ حرف توئه: بدون «روبو:» اولش و بدون توضیحِ اضافه. خط جدید لازم داشتی؟ مثل هر JSONِ معتبر escape کن.");
    lines.push("- داخل text از علامت نقل‌قولِ « » استفاده کن، نه \" (که JSON خراب نشه). فقط داخل بلاک کد، علامت‌های خودِ کد رو مثل هر رشته‌ی JSON درست escape کن.");

    return lines.join("\n");

}

function build(f) {

    return `
━━━━━━━━━━━━━━━━━━━━
فرمت خروجی
━━━━━━━━━━━━━━━━━━━━
دقیقاً یه آبجکت JSON، بدون بک‌تیک، بدون توضیح قبل یا بعدش:

${schema(f)}

${fields(f)}
`.trim();

}

// آخرِ پرامپت می‌شینه (جایی که مدل بیشتر دقت می‌کنه)
function final() {

    return `
━━━━━━━━━━━━━━━━━━━━
چک‌لیستِ قبل از جواب (توی ذهنت)
━━━━━━━━━━━━━━━━━━━━
۱. اصلاً لازمه جواب بدم؟ (ignore یا یه ریکشن شاید بهتر باشه)
۲. حرفم درست و معنادار؟ چیزی از خودم نساختم؟
۳. چاپلوسی، تعریفِ الکی یا موافقتِ بی‌دلیل توشه؟ حذفش کن.
۴. ادعایی رو که کسی بدون دلیل کرده نپذیرفتم؟ فشار و اصرار جوابم رو عوض نکرده؟
۵. کوتاه‌ترین نسخه‌ی کامل و درسته؟ مقدمه، جمع‌بندی و «پیشنهاد کمک» آخرش رو بنداز.
۶. دما و لحنم به طرف و لحظه می‌خوره؟ خط قرمز رد نشده؟ تکراری نیست؟
۷. تعارف یا کوچک‌کردنِ خودم (چشم، در خدمتم، قربان) توش نیست؟
`.trim();

}

module.exports = { build, final, schema };