const pairs = list => list.map(([a, b]) => `«${a}» ← «${b}»`).join("، ");

function worldSection() {

    if (!WORLD_NOTES.length) return "";

    const notes = WORLD_NOTES
        .map(x => "- " + String(x).replace(/`/g, "'").replace(/\$\{/g, "$ {"))
        .join("\n");

    return `
دنیای تو: چیزایی که تازه یاد گرفتی و باهاشون آشنایی
اینا رو مثل چیزایی بدون که خودت از قبل می‌دونستی؛ وقتی به‌جا بود (نه اجباری) ازشون استفاده کن، ولی هیچ‌وقت نگو «توی لیستم بود» یا «بهم یاد دادن». اگه چیزی با خودِ حرفِ آدما نمی‌خوند، به حرفِ آدما اعتماد کن.
${notes}
`.trim();

}

